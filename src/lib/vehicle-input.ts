// Госномер и VIN, как их набирают за стойкой. Чистые правила: их зовёт и
// форма записи (проверить, что человек набрал), и свод машин (понять, что
// две записи — про одну машину).
//
// ЗАЧЕМ VIN, если есть номер. Номер перебивают, машину продают с новым
// номером, а «Лада Веста 2021» в городе не одна. VIN выбит на кузове, живёт
// с машиной до утилизации и один на весь мир — по нему история ремонта
// остаётся при машине, а не при бумажке. Поэтому в ручной записи его
// спрашивают, а не «если вдруг вспомнят».
//
// КИРИЛЛИЦА. «А123АВ» с русской раскладки и «A123AB» с латинской — один и
// тот же номер, набранный двумя способами, и склеиться они обязаны. В VIN по
// стандарту латиница, но с телефона легко влететь кириллицей. Поэтому для
// СРАВНЕНИЯ буквы схлопываем к латинице, а в записи храним ровно то, что
// человек набрал: в отчёт и клиенту уезжает его написание.

/** Кириллица, неотличимая от латиницы на табличке и в VIN. */
const LOOKALIKE: Record<string, string> = {
  А: "A", В: "B", Е: "E", К: "K", М: "M", Н: "H", О: "O", Р: "P", С: "C", Т: "T", У: "Y", Х: "X",
};

/** Верхний регистр плюс кириллица к латинице — вид, в котором можно сравнивать. */
export function foldLookalike(raw: string): string {
  return raw.toUpperCase().replace(/[А-ЯЁ]/g, ch => LOOKALIKE[ch] ?? ch);
}

/** Длина VIN по стандарту — она же единственное, что человек помнит про него. */
export const VIN_LENGTH = 17;

/**
 * VIN к сравнимому виду: без пробелов и дефисов, латиница, 17 знаков.
 * null — это не VIN, и выдавать его за VIN нельзя: по чужому «похожему»
 * номеру склеятся две разные машины.
 */
export function normalizeVin(raw: string | null | undefined): string | null {
  const s = foldLookalike((raw ?? "").replace(/[\s-]+/g, ""));
  return /^[A-HJ-NPR-Z0-9]{17}$/.test(s) ? s : null;
}

/**
 * Что сказать человеку про набранный VIN. null — всё хорошо или поле пустое
 * (VIN не обязателен: машина с улицы без документов приезжает тоже).
 *
 * Сообщения объясняют ошибку, а не ругают: «I, O и Q не бывает» — это самая
 * частая опечатка, буквы путают с единицей и нулём.
 */
export function vinProblem(raw: string | null | undefined): string | null {
  const s = foldLookalike((raw ?? "").replace(/[\s-]+/g, ""));
  if (!s) return null;
  if (normalizeVin(s)) return null;
  if (/[IOQ]/.test(s)) return "В VIN не бывает букв I, O и Q — это единица и ноль";
  if (/[^A-Z0-9]/.test(s)) return "VIN — только латинские буквы и цифры";
  return `VIN — ${VIN_LENGTH} знаков, а набрано ${s.length}`;
}

/** Сколько знаков госномера хватает, чтобы он вообще был номером. */
const PLATE_MIN = 4;

/**
 * Госномер так, как он попадёт в запись: без лишних пробелов, в верхнем
 * регистре и написанием человека. Сравнивать его будет normalizePlate
 * (lib/vehicles.ts) — там кириллица схлопывается, здесь нет.
 */
export function plateInput(raw: string | null | undefined): string | null {
  const s = (raw ?? "").trim().replace(/\s+/g, " ").toUpperCase().slice(0, 12);
  return s.replace(/[\s-]+/g, "").length >= PLATE_MIN ? s : null;
}

/** «Похоже на номер, но коротко» — единственная ошибка, о которой стоит сказать. */
export function plateProblem(raw: string | null | undefined): string | null {
  const s = (raw ?? "").trim();
  if (!s) return null;
  return plateInput(s) ? null : "Госномер короче, чем бывает — проверьте";
}
