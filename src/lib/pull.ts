// Правила жеста «потяни вниз — обновится»: по пути пальца решаем, наш это
// жест или экрана. Отдельно от компонента (components/PullRefresh.tsx),
// потому что ошибаются тут не в разметке, а в числах и знаках: перехватишь
// лишнее — и таймлайн не прокрутить, недоберёшь — жест не срабатывает.
//
// Все числа — в пикселях пути пальца от точки касания.

/** Дальше этой отметки отпустили — обновляем. */
export const PULL_TRIGGER = 72;
/** Дальше кружок не идёт: палец тянет, экран не резинится. */
export const PULL_MAX = 108;
/** Пока не понятно, тянут вниз или листают вбок, жест не наш. */
export const PULL_SLOP = 8;
/** Кружок отстаёт от пальца — так жест ощущается натяжением, а не рывком. */
const RESIST = 0.55;

export type PullMove =
  /** Ещё не разобрать: ничего не перехватываем и ждём следующего движения. */
  | { kind: "wait" }
  /** Жест экрана — прокрутка или листание вбок. Больше в него не лезем. */
  | { kind: "drop" }
  /** Наш: столько пикселей кружок прошёл вниз. */
  | { kind: "pull"; dist: number };

/**
 * `mine` — жест уже признан нашим на прошлом движении: тогда решение принято
 * и палец можно вести куда угодно, в том числе назад вверх (натяжение просто
 * сойдёт в ноль, и на отпускании ничего не обновится).
 */
export function pullMove(mine: boolean, dy: number, dx: number): PullMove {
  if (!mine) {
    if (dy < -PULL_SLOP || (Math.abs(dx) > PULL_SLOP && Math.abs(dx) > Math.abs(dy))) return { kind: "drop" };
    if (dy < PULL_SLOP) return { kind: "wait" };
  }
  return { kind: "pull", dist: Math.min(PULL_MAX, Math.max(0, (dy - PULL_SLOP) * RESIST)) };
}
